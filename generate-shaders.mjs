import { URL } from 'node:url'
// Inlines the GLSL sources into a TypeScript module, so the package needs no bundler or runtime fetch.
// Brush headers are parsed here; see src/brushes/README.md for the format.
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises'

const source = new URL('./src/', import.meta.url)
const read = async (path) =>
  (await readFile(new URL(path, source), 'utf8')).replaceAll('\r\n', '\n')
const param =
  /^\/\/ @param (outline|shading)\.([A-Za-z]\w*)\s+(float|range)\s+(\S+)\s+(-?[\d.]+)\.\.(-?[\d.]+)\s+(.+)$/

function parseBrush(file, text) {
  const name = text.match(/^\/\/ @brush ([a-z][a-z0-9-]*)$/m)?.[1]
  if (!name) throw new Error(`${file}: missing "// @brush <name>" line`)
  const params = []
  for (const line of text.split('\n')) {
    if (!line.startsWith('// @param ')) continue
    const match = line.match(param)
    if (!match) throw new Error(`${file}: cannot parse "${line}"`)
    const [, layer, key, type, value, min, max, description] = match
    const defaults = value.split(',').map(Number)
    if (
      defaults.length !== (type === 'range' ? 2 : 1) ||
      !defaults.every(Number.isFinite)
    )
      throw new Error(`${file}: bad default in "${line}"`)
    const bounds = [Number(min), Number(max)]
    if (!bounds.every(Number.isFinite) || bounds[0] >= bounds[1])
      throw new Error(`${file}: bad range in "${line}"`)
    if (!defaults.every((v) => v >= bounds[0] && v <= bounds[1]))
      throw new Error(`${file}: default outside its range in "${line}"`)
    if (type === 'range' && defaults[0] >= defaults[1])
      throw new Error(`${file}: range default must increase in "${line}"`)
    if (params.some((p) => p.layer === layer && p.key === key))
      throw new Error(`${file}: duplicate ${layer}.${key}`)
    params.push({
      layer,
      key,
      type,
      default: type === 'range' ? defaults : defaults[0],
      min: bounds[0],
      max: bounds[1],
      description: description.trim(),
    })
  }
  for (const layer of ['outline', 'shading'])
    if (
      !params.some(
        (p) => p.layer === layer && p.key === 'opacity' && p.type === 'float',
      )
    )
      throw new Error(
        `${file}: declare "${layer}.opacity" as a float parameter`,
      )
  return { name, params, source: text }
}

const brushes = {}
// Each brush is a folder in src/brushes with a GLSL file of the same name.
for (const entry of (
  await readdir(new URL('brushes/', source), { withFileTypes: true })
).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue
  const file = `${entry.name}/${entry.name}.glsl`
  const brush = parseBrush(file, await read(`brushes/${file}`))
  if (brushes[brush.name]) throw new Error(`Duplicate brush ${brush.name}`)
  brushes[brush.name] = brush
}

const output = `// Generated by generate-shaders.mjs from src/core/shaders and src/brushes. Do not edit.
export const vertexShader = ${JSON.stringify(await read('core/shaders/vertex.glsl'))}
export const preludeShader = ${JSON.stringify(await read('core/shaders/prelude.glsl'))}
export const composeShader = ${JSON.stringify(await read('core/shaders/compose.glsl'))}
export const brushSources = ${JSON.stringify(brushes, null, 2)} as const
`
await mkdir(new URL('generated/', source), { recursive: true })
await writeFile(new URL('generated/shaders.ts', source), output)
